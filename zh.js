function tr_value(s) {
	var t = s.trim()
	if (VALUES[t] !== undefined)
		return s.replace(t, VALUES[t])
	var m = /^([A-Z][a-z]+) (\d{4})$/.exec(t)
	if (m && MONTHS[m[1]])
		return s.replace(t, m[2] + "年" + MONTHS[m[1]])
	return s
}

function translate(text) {
	if (typeof text !== "string" || text === "")
		return text
	var hit = memo.get(text)
	if (hit !== undefined)
		return hit
	var out
	if (EXACT[text] !== undefined) {
		out = EXACT[text]
	} else {
		out = text
		for (var i = 0; i < REGEXES.length; ++i) {
			var r = REGEXES[i]
			if (!/[A-Za-z]/.test(out))
				break
			r.re.lastIndex = 0
			out = out.replace(r.re, function () {
				var args = arguments
				return r.zh.replace(/\{(\d+)\}/g, function (_, n) {
					var gi = r.order.indexOf(+n) + 1
					var captured = args[gi]
					if (EXACT[captured] !== undefined)
						return EXACT[captured]
					return tr_value(captured)
				})
			})
		}
		// final pass: translate bare values (faction names etc.)
		if (out === text && VALUES[text.trim()] !== undefined)
			out = tr_value(out)
		// month-year fragments, e.g. "August 1914"
		out = out.replace(/([A-Z][a-z]+) (\d{4})/g, function (mm, mon, yr) {
			return MONTHS[mon] ? yr + "年" + MONTHS[mon] : mm
		})
	}
	memo.set(text, out)
	if (memo.size > 20000)
		memo.clear()
	return out
}

