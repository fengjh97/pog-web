var EXACT = {}
var REGEXES = []
function esc_re(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") }
for (var i = 0; i < PAIRS.length; ++i) {
	var en_t = PAIRS[i][0], zh_t = PAIRS[i][1]
	if (en_t.indexOf("{") < 0) {
		EXACT[en_t] = zh_t
	} else {
		var src = esc_re(en_t).replace(/\\\{(\d+)\\\}/g, "(.+?)")
		var order = []
		en_t.replace(/\{(\d+)\}/g, function (_, n) { order.push(+n); return "" })
		REGEXES.push({
			re: new RegExp(src, "g"),
			zh: zh_t,
			order: order,
			len: en_t.replace(/\{\d+\}/g, "").length,
		})
	}
}
REGEXES.sort(function (a, b) { return b.len - a.len })

